import { useNavigate, useParams } from "react-router-dom";
import { useEffect, useState } from "react";
import { ShieldCheck, XCircle, Loader2 } from "lucide-react";
import Page from "../components/Page";
import GlassCard from "../components/GlassCard";
import { getPublicVerification } from "../utils/audit";

export default function Verify() {
  const { id } = useParams();
  const navigate = useNavigate();
  const [status, setStatus] = useState("idle"); // idle | loading | verified | not_found
  const [decisionId, setDecisionId] = useState(id || "");
  const [audit, setAudit] = useState(null);

  useEffect(() => {
    if (!id) return;
    setStatus("loading");
    getPublicVerification(id)
      .then((data) => { setAudit(data); setStatus("verified"); })
      .catch(() => setStatus("not_found"));
  }, [id]);

  const submit = (e) => {
    e.preventDefault();
    const trimmed = decisionId.trim();
    if (trimmed) navigate(`/verify/${encodeURIComponent(trimmed)}`);
  };

  return (
    <Page>
      <section className="mx-auto max-w-xl px-6 py-20">
        <div className="mb-8 text-center">
          <span className="eyebrow"><ShieldCheck size={14} /> Report Verification</span>
          <h1 className="mt-4 text-3xl font-bold">Verify a <span className="gradient-text">Report</span></h1>
          <p className="mt-3 text-sm text-slate-400">
            Enter the verification code printed on your EchoLedger report to confirm it was genuinely issued by our system.
          </p>
        </div>

        <GlassCard>
          <form onSubmit={submit} className="space-y-4">
            <label className="block text-sm font-medium text-slate-300">
              Verification Code
              <input
                value={decisionId}
                onChange={(e) => setDecisionId(e.target.value)}
                placeholder="Paste the code from your report"
                className="mt-2 w-full rounded-xl border border-slate-700 bg-slate-900 px-4 py-3 font-mono text-sm text-white outline-none transition focus:border-cyan-500 focus:ring-2 focus:ring-cyan-500/20"
              />
            </label>
            <button type="submit" className="btn-primary w-full">
              Verify Report
            </button>
          </form>

          {/* Loading */}
          {status === "loading" && (
            <div className="mt-6 flex items-center justify-center gap-2 text-slate-400">
              <Loader2 size={18} className="animate-spin" />
              <span className="text-sm">Checking our records…</span>
            </div>
          )}

          {/* Verified */}
          {status === "verified" && (
            <div className="mt-6 rounded-xl border border-emerald-500/30 bg-emerald-500/10 p-5">
              <div className="flex items-center gap-3">
                <ShieldCheck size={28} className="shrink-0 text-emerald-400" />
                <div>
                  <p className="font-semibold text-emerald-300">✓ Authentic EchoLedger Report</p>
                  <p className="mt-1 text-sm text-slate-300">
                    This report was genuinely generated by EchoLedger and has not been tampered with.
                  </p>
                </div>
              </div>
              <div className="mt-4 grid grid-cols-2 gap-3 border-t border-white/10 pt-4 text-xs text-slate-400">
                <div>
                  <p className="text-slate-500">Issued on</p>
                  <p className="mt-0.5 font-medium text-white">
                    {audit?.createdAt ? new Date(audit.createdAt).toLocaleDateString("en-IN", { day: "numeric", month: "long", year: "numeric" }) : "—"}
                  </p>
                </div>
                <div>
                  <p className="text-slate-500">Status</p>
                  <p className="mt-0.5 font-medium text-emerald-300 capitalize">{audit?.status || "Complete"}</p>
                </div>
              </div>
            </div>
          )}

          {/* Not found */}
          {status === "not_found" && (
            <div className="mt-6 rounded-xl border border-rose-500/30 bg-rose-500/10 p-5">
              <div className="flex items-center gap-3">
                <XCircle size={24} className="shrink-0 text-rose-400" />
                <div>
                  <p className="font-semibold text-rose-300">Report not found</p>
                  <p className="mt-1 text-sm text-slate-400">
                    No EchoLedger report matches this code. Please check the code and try again.
                  </p>
                </div>
              </div>
            </div>
          )}
        </GlassCard>
      </section>
    </Page>
  );
}
