import { Link, useNavigate, useParams } from "react-router-dom";
import { Download, FileSearch, ShieldCheck, ThumbsDown, Anchor, BadgeCheck } from "lucide-react";
import { isBlockchainConfigured, isRegistryConfigured } from "../blockchain/simpleDispute";
import { jsPDF } from "jspdf";
import Page from "../components/Page";
import GlassCard from "../components/GlassCard";
import Button from "../components/Button";
import { ConfidenceMeter, RiskMeter } from "../components/Meters";
import { DecisionInsights } from "../components/DecisionInsights";
import OnChainVerification from "../components/OnChainVerification";
import { getAudit } from "../utils/audit";
import { useEffect, useState } from "react";

export default function Decision() {
  const [audit, setAudit] = useState(null);
  const [error, setError] = useState("");
  const navigate = useNavigate();
  const { id } = useParams();
  useEffect(() => {
    getAudit(id).then(setAudit).catch(() => setError("Decision record not found or you are not signed in."));
  }, [id]);

  if (error) return <Page><p className="mx-auto max-w-5xl px-6 py-20 text-rose-300">{error}</p></Page>;
  if (!audit) return <Page><p className="mx-auto max-w-5xl px-6 py-20 text-slate-400">Loading decision record…</p></Page>;

  const { result, application } = audit;
  const approved = result.decision?.toLowerCase().includes("approv") || result.decision?.toLowerCase().includes("eligible") || result.decision?.toLowerCase().includes("shortlist") || result.decision?.toLowerCase().includes("admit") || result.decision?.toLowerCase().includes("standard");

  const exportPdf = () => {
    const pdf = new jsPDF("p", "mm", "a4");
    const margin = 18;
    const maxWidth = 174;
    let y = 22;
    let pageCount = 1;

    const drawFooter = () => {
      pdf.setFont("helvetica", "normal");
      pdf.setTextColor(100, 116, 139);
      pdf.setFontSize(8);
      pdf.text("Generated by EchoLedger — The Trust Layer for AI Decisions", margin, 285);
      pdf.text(`Page ${pageCount}`, 185, 285, { align: "right" });
    };

    const newPage = () => {
      drawFooter();
      pdf.addPage();
      pageCount++;
      // Fill dark background
      pdf.setFillColor(2, 6, 23);
      pdf.rect(0, 0, 210, 297, "F");
      y = 22;
      // Header
      pdf.setTextColor(96, 165, 250);
      pdf.setFontSize(12);
      pdf.text("ECHOLEDGER  /  VERIFIED DECISION RECORD", margin, y);
      y += 15;
      pdf.setTextColor(255, 255, 255);
      pdf.setFontSize(25);
      pdf.setFont("helvetica", "bold");
      pdf.text(result.decision || "Decision", margin, y);
      y += 9;
      pdf.setFontSize(10);
      pdf.setFont("helvetica", "normal");
      pdf.setTextColor(148, 163, 184);
      pdf.text(`${audit.id}  •  ${new Date(audit.createdAt).toLocaleString()}`, margin, y);
      y += 8;
      pdf.setDrawColor(51, 65, 85);
      pdf.line(margin, y, 192, y);
      y += 10;
    };

    const checkSpace = (needed) => {
      if (y + needed > 275) newPage();
    };

    const write = (label, value) => {
      checkSpace(10);
      pdf.setFont("helvetica", "bold");
      pdf.setTextColor(226, 232, 240);
      pdf.setFontSize(11);
      pdf.text(label, margin, y);
      pdf.setFont("helvetica", "normal");
      pdf.text(pdf.splitTextToSize(String(value || "—"), 150), 52, y);
      y += 10;
    };

    const writeParagraph = (text, fontSize = 10, indent = 0, color = "#cbd5e1") => {
      checkSpace(15);
      pdf.setFont("helvetica", "normal");
      pdf.setTextColor(color);
      pdf.setFontSize(fontSize);
      const lines = pdf.splitTextToSize(text || "", maxWidth - indent);
      lines.forEach((line) => {
        checkSpace(6);
        pdf.text(line, margin + indent, y);
        y += 5;
      });
    };

    const sectionTitle = (title) => {
      checkSpace(20);
      pdf.setFillColor(30, 41, 59);
      pdf.roundedRect(margin, y - 5, maxWidth, 10, 2, 2, "F");
      pdf.setFont("helvetica", "bold");
      pdf.setTextColor(125, 211, 252);
      pdf.setFontSize(11);
      pdf.text(title.toUpperCase(), margin + 4, y + 1.5);
      y += 12;
    };

    // === FIRST PAGE ===
    // Fill dark background
    pdf.setFillColor(2, 6, 23);
    pdf.rect(0, 0, 210, 297, "F");

    // Header
    pdf.setTextColor(96, 165, 250);
    pdf.setFontSize(12);
    pdf.text("ECHOLEDGER  /  VERIFIED DECISION RECORD", margin, y);
    y += 15;
    pdf.setTextColor(255, 255, 255);
    pdf.setFontSize(25);
    pdf.setFont("helvetica", "bold");
    pdf.text(result.decision || "Decision", margin, y);
    y += 9;
    pdf.setFontSize(10);
    pdf.setFont("helvetica", "normal");
    pdf.setTextColor(148, 163, 184);
    pdf.text(`${audit.id}  •  ${new Date(audit.createdAt).toLocaleString()}`, margin, y);
    y += 8;
    pdf.setDrawColor(51, 65, 85);
    pdf.line(margin, y, 192, y);
    y += 10;

    // Applicant details (industry-aware)
    const fields = (INDUSTRY_FIELDS[application.industry] || INDUSTRY_FIELDS.banking)(application);
    fields.forEach(({ label, value }) => { if (value) write(label, value); });
    write("Industry", application.industryLabel || application.industry || "Banking");
    write("Outcome", result.decision);
    write("Confidence", `${result.confidence}%`);
    write("Risk level", result.risk);
    y += 3;

    // Section: Decision rationale
    checkSpace(20);
    pdf.setFont("helvetica", "bold");
    pdf.setTextColor(255, 255, 255);
    pdf.setFontSize(13);
    pdf.text("Decision rationale", margin, y);
    y += 8;
    writeParagraph(result.reason || "");

    // Section: Recommended next step
    checkSpace(20);
    pdf.setFont("helvetica", "bold");
    pdf.setTextColor(255, 255, 255);
    pdf.setFontSize(13);
    pdf.text("Recommended next step", margin, y);
    y += 8;
    writeParagraph(result.suggestion || "");

    // Section: Audit trail
    const steps = result.trace || result.reasoningSteps || [];
    if (steps.length > 0) {
      checkSpace(20);
      pdf.setFont("helvetica", "bold");
      pdf.setTextColor(255, 255, 255);
      pdf.setFontSize(13);
      pdf.text("Audit trail", margin, y);
      y += 8;

      steps.forEach((step, index) => {
        checkSpace(20);
        pdf.setFont("helvetica", "bold");
        pdf.setTextColor(148, 163, 184);
        pdf.setFontSize(10);
        pdf.text(`${index + 1}. ${step.title}`, margin + 4, y);
        y += 6;
        writeParagraph(step.detail || "", 9, 8, "#94a3b8");
        y += 3;
      });
    }

    // Section: AI bias detection
    const biasAudit = result.biasAudit;
    if (biasAudit) {
      checkSpace(20);
      pdf.setFont("helvetica", "bold");
      pdf.setTextColor(255, 255, 255);
      pdf.setFontSize(13);
      pdf.text("AI bias detection", margin, y);
      y += 8;
      writeParagraph(biasAudit.note || "");
      y += 2;
      pdf.setFont("helvetica", "normal");
      pdf.setTextColor(148, 163, 184);
      pdf.setFontSize(9);
      checkSpace(6);
      pdf.text(`Excluded: ${(biasAudit.protectedAttributesExcluded || []).join(", ")}`, margin, y);
      y += 5;
      checkSpace(6);
      pdf.text(`Evaluated: ${(biasAudit.evaluatedFactors || []).join(", ")}`, margin, y);
      y += 6;
    }

    // Section: Independent AI reviewer
    if (result.agentReview) {
      checkSpace(25);
      pdf.setFont("helvetica", "bold");
      pdf.setTextColor(255, 255, 255);
      pdf.setFontSize(13);
      pdf.text("Independent AI reviewer", margin, y);
      y += 8;
      pdf.setFont("helvetica", "bold");
      pdf.setTextColor(result.agentReview.disagrees ? "#fbbf24" : "#34d399");
      pdf.setFontSize(11);
      pdf.text(result.agentReview.verdict || "", margin, y);
      y += 7;
      writeParagraph(result.agentReview.reason || "", 9, 0, "#cbd5e1");
      y += 3;
    }

    // Multi-Agent Jury
    if (result.jury) {
      sectionTitle("Multi-Agent AI Jury");
      [["Optimist", result.jury.optimist], ["Risk Assessor", result.jury.riskAssessor], ["Judge", result.jury.judge]].forEach(([role, arg]) => {
        if (!arg) return;
        checkSpace(15);
        pdf.setFont("helvetica", "bold"); pdf.setTextColor(226, 232, 240); pdf.setFontSize(10);
        pdf.text(`${role}: ${arg.position || arg.decision || "Deliberation"}`, margin, y); y += 5;
        writeParagraph(arg.rationale || arg.reason || "No rationale recorded.", 9, 4);
      });
      if (result.jury.judge?.biasCheck) writeParagraph(`Bias check: ${result.jury.judge.biasCheck}`, 9, 0, "#67e8f9");
      y += 3;
    }

    // Section: Tamper-evident hash
    checkSpace(25);
    pdf.setFont("helvetica", "bold");
    pdf.setTextColor(255, 255, 255);
    pdf.setFontSize(13);
    pdf.text("Tamper-evident audit hash", margin, y);
    y += 8;
    pdf.setFont("courier", "normal");
    pdf.setFontSize(8);
    pdf.setTextColor(103, 232, 249);
    writeParagraph(`sha256:${audit.hash}`, 8, 0, "#67e8f9");
    y += 5;

    // If there's still a lot of space left on last page, don't add blank pages
    // Just draw footer on the last page
    drawFooter();
    pdf.save(`${audit.id}-decision-record.pdf`);
  };

  return (
    <Page>
      <section className="mx-auto max-w-5xl px-6 py-14" id="decision-report">
        <div className="flex flex-col justify-between gap-5 sm:flex-row sm:items-start">
          <div>
            <span className="eyebrow"><ShieldCheck size={14} /> Verified decision record</span>
            <h1 className="mt-4 text-4xl font-bold">Decision <span className="gradient-text">explained</span></h1>
            <p className="mt-2 text-slate-400">{audit.id} · {new Date(audit.createdAt).toLocaleString()}</p>
          </div>
          <button onClick={exportPdf} className="secondary-btn"><Download size={17} /> Export PDF</button>
        </div>

        <div className="mt-9 grid gap-6 lg:grid-cols-5">
          <GlassCard className="lg:col-span-3">
            <p className="text-sm text-slate-400">Application outcome</p>
            <div className="mt-3 flex flex-wrap items-center justify-between gap-4">
              <h2 className="text-3xl font-bold">{result.decision}</h2>
              <span className={`rounded-full px-3 py-1 text-sm font-semibold ${approved ? "bg-emerald-500/15 text-emerald-300" : "bg-amber-500/15 text-amber-200"}`}>
                {approved ? "Policy eligible" : "Human review"}
              </span>
            </div>
            <div className="mt-7 space-y-6">
              <ConfidenceMeter value={result.confidence} />
              <RiskMeter risk={result.risk} />
            </div>
            <div className="mt-8 grid gap-4 border-t border-white/10 pt-6 sm:grid-cols-2">
              <IndustryDetails application={application} />
            </div>
          </GlassCard>

          <div className="space-y-6 lg:col-span-2">
            <GlassCard>
              <FileSearch className="text-violet-400" />
              <h3 className="mt-4 text-lg font-semibold">Why this outcome?</h3>
              <p className="mt-3 text-sm leading-6 text-slate-400">{result.reason}</p>
            </GlassCard>
            <GlassCard>
              <h3 className="text-lg font-semibold">Recommended next step</h3>
              <p className="mt-3 text-sm leading-6 text-slate-400">{result.suggestion}</p>
            </GlassCard>
          </div>
        </div>

        <GlassCard className="mt-6">
          <p className="text-xs font-semibold uppercase tracking-wider text-slate-500">Tamper-evident decision hash</p>
          <code className="mt-3 block break-all rounded-lg bg-black/20 p-3 text-xs text-cyan-300">sha256:{audit.hash}</code>

          {/* Blockchain status indicators */}
          <div className="mt-4 flex flex-wrap gap-3">
            {audit.onChainAnchor && (
              <span className="inline-flex items-center gap-1.5 rounded-full bg-emerald-500/15 px-3 py-1 text-xs font-medium text-emerald-300">
                <Anchor size={12} /> Anchored on-chain
              </span>
            )}
            {audit.onChainCommit && (
              <span className="inline-flex items-center gap-1.5 rounded-full bg-emerald-500/15 px-3 py-1 text-xs font-medium text-emerald-300">
                <BadgeCheck size={12} /> Committed on-chain
              </span>
            )}
            {audit.blockchain && (
              <span className="inline-flex items-center gap-1.5 rounded-full bg-blue-500/15 px-3 py-1 text-xs font-medium text-blue-300">
                <BadgeCheck size={12} /> Blockchain tx: {audit.blockchain.transactionHash?.slice(0, 10)}…
              </span>
            )}
            {audit.agentChallenge && (
              <span className="inline-flex items-center gap-1.5 rounded-full bg-amber-500/15 px-3 py-1 text-xs font-medium text-amber-300">
                <ThumbsDown size={12} /> Automated challenge submitted
              </span>
            )}
            {!audit.onChainAnchor && !audit.onChainCommit && !audit.blockchain && (
              <span className="inline-flex items-center gap-1.5 rounded-full bg-slate-500/15 px-3 py-1 text-xs font-medium text-slate-400">
                Not yet anchored on-chain
              </span>
            )}
          </div>
        </GlassCard>

        <div className="mt-6">
          <DecisionInsights application={application} result={result} hash={audit.hash} />
        </div>
        <div className="mt-6"><OnChainVerification decisionId={id} expectedHash={audit.hash} /></div>
        <div className="mt-8 flex flex-wrap gap-3">
          <Link to={`/trace/${id}`}><Button>View audit trail</Button></Link>
          <Link to={`/challenge/${id}`} className="secondary-btn"><ThumbsDown size={17} /> Challenge decision</Link>
        </div>
      </section>
    </Page>
  );
}

function Detail({ label, value }) {
  return (
    <div>
      <p className="text-xs text-slate-500">{label}</p>
      <p className="mt-1 font-medium">{value || "—"}</p>
    </div>
  );
}

const INDUSTRY_FIELDS = {
  banking:          (a) => [{ label: "Applicant", value: a.name }, { label: "Email", value: a.email }, { label: "Phone", value: a.phone }, { label: "Date of birth", value: a.dob }, { label: "Requested amount", value: `₹${Number(a.loanAmount || 0).toLocaleString("en-IN")}` }, { label: "Employment", value: a.employment }, { label: "Credit score", value: a.creditScore }, { label: "Age", value: a.age ? `${a.age} years` : null }],
  insurance:        (a) => [{ label: "Applicant", value: a.name }, { label: "Email", value: a.email }, { label: "Policy type", value: a.policyType }, { label: "Coverage amount", value: `₹${Number(a.coverageAmount || 0).toLocaleString("en-IN")}` }, { label: "Smoking status", value: a.smokingStatus }, { label: "Occupation", value: a.occupation }, { label: "Pre-existing conditions", value: a.preExistingConditions }, { label: "Age", value: a.age ? `${a.age} years` : null }],
  hiring:           (a) => [{ label: "Candidate", value: a.name }, { label: "Email", value: a.email }, { label: "Role applied for", value: a.role }, { label: "Experience", value: `${a.yearsExperience} years` }, { label: "Education", value: a.education }, { label: "Skills", value: a.skills }, { label: "Current CTC", value: a.currentCTC ? `₹${Number(a.currentCTC).toLocaleString("en-IN")}` : null }, { label: "Expected CTC", value: a.expectedCTC ? `₹${Number(a.expectedCTC).toLocaleString("en-IN")}` : null }],
  healthcare:       (a) => [{ label: "Patient", value: a.name }, { label: "Email", value: a.email }, { label: "Phone", value: a.phone }, { label: "Date of birth", value: a.dob }, { label: "Condition", value: a.condition }, { label: "Requested treatment", value: a.requestedTreatment }, { label: "Insurance coverage", value: a.insuranceCoverage }, { label: "Urgency", value: a.urgency }],
  government:       (a) => [{ label: "Applicant", value: a.name }, { label: "Email", value: a.email }, { label: "Phone", value: a.phone }, { label: "Annual income", value: `₹${Number(a.annualIncome || 0).toLocaleString("en-IN")}` }, { label: "Household size", value: a.householdSize }, { label: "Benefit type", value: a.benefitType }, { label: "Employment status", value: a.employmentStatus }, { label: "State", value: a.state }],
  education:        (a) => [{ label: "Applicant", value: a.name }, { label: "Email", value: a.email }, { label: "Program", value: a.program }, { label: "Institution", value: a.institution }, { label: "GPA", value: `${a.gpa} / 10` }, { label: "Entrance score", value: `${a.entranceScore} percentile` }, { label: "Financial need", value: a.financialNeed }, { label: "Age", value: a.age ? `${a.age} years` : null }],
  "customer-support": (a) => [{ label: "Customer", value: a.name }, { label: "Email", value: a.email }, { label: "Phone", value: a.phone }, { label: "Product", value: a.productName }, { label: "Issue type", value: a.issueType }, { label: "Severity", value: a.severity }, { label: "Previous tickets", value: a.previousTickets }, { label: "Resolution requested", value: a.resolutionRequested }],
};

function IndustryDetails({ application }) {
  const fields = (INDUSTRY_FIELDS[application.industry] || INDUSTRY_FIELDS.banking)(application);
  return fields.map(({ label, value }) => <Detail key={label} label={label} value={value} />);
}
